import type { ConstraintKind, ReferentialAction, TriggerEvent } from '../db/introspect'

/**
 * Condições que a validação confere no banco real do aluno.
 * Tipos de coluna usam o formato do Postgres (format_type): 'integer', 'character varying(100)',
 * 'date', 'timestamp without time zone', 'numeric(10,2)', 'boolean', 'text'.
 */
export type CheckSpec =
  | { kind: 'tableExists'; table: string }
  | { kind: 'tableMissing'; table: string }
  | {
      kind: 'column'
      table: string
      name: string
      type?: string
      nullable?: boolean
      primaryKey?: boolean
      unique?: boolean
      /** IDENTITY ou SERIAL. */
      autoGenerated?: boolean
      hasDefault?: boolean
    }
  | {
      kind: 'constraint'
      table: string
      constraint: ConstraintKind
      columns?: string[]
      refTable?: string
      onDelete?: ReferentialAction
    }
  | { kind: 'rowCount'; table: string; where?: string; equals?: number; atLeast?: number }
  /** `sql` deve devolver uma única célula booleana. */
  | { kind: 'sqlTrue'; sql: string; label: string; message?: string }
  /** Regex (padrão: case-insensitive) sobre o SQL que o aluno executou neste passo. */
  | { kind: 'sqlMatches'; pattern: string; label: string; flags?: string; raw?: boolean }
  /**
   * Compara o resultado da última execução com o de `expectedSql`.
   * Atenção: `expectedSql` roda sobre o banco ATUAL, que a resposta do aluno pode ter alterado.
   * Em passos que mudam dados, valide as mudanças com rowCount/sqlTrue e use isto só para a consulta.
   */
  | { kind: 'resultMatches'; expectedSql: string; ordered?: boolean; ignoreColumnNames?: boolean }
  /** A última execução deve ter dado erro (opcionalmente com este SQLSTATE). */
  | { kind: 'lastRunError'; code?: string }
  /** A última execução terminou com uma transação aberta e o motor a desfez (BEGIN sem COMMIT). */
  | { kind: 'lastRunRolledBack'; label: string }
  /** `name` é o nome simples ou qualificado (`relatorios.vendas`). */
  | { kind: 'view'; name: string; materialized?: boolean }
  /** Qualquer função com este nome, seja qual for a lista de argumentos. */
  | { kind: 'function'; name: string }
  /** Algum trigger da tabela (opcionalmente com este nome, momento e evento). */
  | { kind: 'trigger'; table: string; name?: string; timing?: 'BEFORE' | 'AFTER' | 'INSTEAD OF'; event?: TriggerEvent }
  /** Algum índice (que não seja o da chave primária) com estas características; `columns` na ordem exata. */
  | { kind: 'index'; table: string; columns?: string[]; unique?: boolean; partial?: boolean; method?: string }
  /** O texto das linhas do último resultado casa com a regex (ex.: o plano de um EXPLAIN mostra "Index Scan"). */
  | { kind: 'resultText'; pattern: string; flags?: string; label: string }

export type Check = CheckSpec & { label?: string }

export interface Step {
  id: string
  title: string
  /** Objetivo em markdown curto. */
  goal: string
  /** Por que isso importa na loja (markdown curto). */
  context?: string
  starter?: string
  /** Dicas progressivas: cada uma revelada custa XP. */
  hints: string[]
  /** Solução de referência: também define o estado do banco para os passos seguintes. */
  solution: string
  /** A solução deve falhar de propósito (passo que ensina a ler erros). */
  expectError?: boolean
  /** Respostas erradas típicas: o teste de conteúdo garante que NÃO passam. */
  wrong?: string[]
  checks: Check[]
  /** XP base do passo (padrão em game/xp.ts). */
  xp?: number
}

export interface Lesson {
  id: string
  title: string
  summary: string
  /** Teoria em markdown, mostrada antes da prática. */
  theory: string
  steps: Step[]
  /** Chefão do módulo: desafio só com requisito de negócio. */
  boss?: boolean
}

export interface Module {
  id: string
  title: string
  subtitle: string
  emoji: string
  lessons: Lesson[]
}
