import type { Engine, RunOutcome, StatementResult } from '../db/engine'
import { EMPTY_SCHEMA, introspect, type SchemaModel, type TableModel } from '../db/introspect'
import type { Check } from './types'

export interface Submission {
  /** Todo o SQL executado com sucesso durante este passo (para os checks sqlMatches). */
  sql: string
  /** Resultado da última execução (para resultMatches e lastRunError). */
  lastOutcome: RunOutcome | null
}

export interface CheckResult {
  ok: boolean
  label: string
  /** Explicação do que ainda falta, quando !ok. */
  message?: string
}

export function describeCheck(check: Check): string {
  if (check.label) return check.label
  switch (check.kind) {
    case 'tableExists':
      return `Existe a tabela \`${check.table}\``
    case 'tableMissing':
      return `A tabela \`${check.table}\` não existe mais`
    case 'column': {
      const parts = [
        check.type && `tipo ${check.type}`,
        check.nullable === false && 'obrigatória (NOT NULL)',
        check.nullable === true && 'opcional (aceita NULL)',
        check.primaryKey && 'chave primária',
        check.unique && 'única',
        check.autoGenerated && 'gerada automaticamente',
        check.hasDefault && 'com valor padrão (DEFAULT)',
      ].filter(Boolean)
      return `Coluna \`${check.table}.${check.name}\`${parts.length ? ': ' + parts.join(', ') : ''}`
    }
    case 'constraint': {
      const names = { primary: 'chave primária', unique: 'UNIQUE', foreign: 'chave estrangeira', check: 'CHECK' }
      return `\`${check.table}\` tem ${names[check.constraint]}${check.columns ? ` em (${check.columns.join(', ')})` : ''}${check.refTable ? ` → \`${check.refTable}\`` : ''}`
    }
    case 'rowCount': {
      const cond = check.where ? ` onde ${check.where}` : ''
      if (check.equals !== undefined) return `\`${check.table}\`${cond} tem exatamente ${check.equals} linha(s)`
      return `\`${check.table}\`${cond} tem pelo menos ${check.atLeast} linha(s)`
    }
    case 'resultMatches':
      return 'O resultado da sua consulta é o esperado'
    case 'lastRunError':
      return check.code ? `A execução deu o erro ${check.code}` : 'A execução deu erro'
    case 'view':
      return `Existe a ${check.materialized ? 'view materializada' : 'view'} \`${check.name}\``
    case 'function':
      return `Existe a função \`${check.name}\``
    case 'trigger': {
      const parts = [check.timing, check.event].filter(Boolean).join(' ')
      return `\`${check.table}\` tem um trigger${check.name ? ` \`${check.name}\`` : ''}${parts ? ` (${parts})` : ''}`
    }
    case 'index': {
      const parts = [
        check.unique && 'único',
        check.partial && 'parcial',
        check.method,
        check.columns && `sobre (${check.columns.join(', ')})`,
      ].filter(Boolean)
      return `\`${check.table}\` tem um índice${parts.length ? ' ' + parts.join(', ') : ''}`
    }
    case 'sqlTrue':
    case 'sqlMatches':
    case 'resultText':
    case 'lastRunRolledBack':
      return check.label
  }
}

const sameSet = (a: string[], b: string[]) => a.length === b.length && a.every((x) => b.includes(x))

function stripComments(sql: string) {
  return sql.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/--[^\n]*/g, ' ')
}

/**
 * Normaliza um valor para comparação. Números e textos numéricos ("12.00" do tipo numeric)
 * viram o mesmo valor: o aluno pode calcular com inteiros ou decimais e chegar ao mesmo resultado.
 */
function normalizeCell(v: unknown): string {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'bigint' || typeof v === 'number') return String(Number(v))
  if (typeof v === 'string' && /^-?\d+(\.\d+)?$/.test(v)) return String(Number(v))
  if (v instanceof Date) return v.toISOString()
  return JSON.stringify(v)
}

const lastTable = (outcome: RunOutcome): StatementResult | undefined =>
  outcome.ok ? [...outcome.results].reverse().find((r) => r.columns.length > 0) : undefined

type Verdict = { ok: true } | { ok: false; message: string }
const pass: Verdict = { ok: true }
const fail = (message: string): Verdict => ({ ok: false, message })

function checkColumn(check: Extract<Check, { kind: 'column' }>, table: TableModel | undefined): Verdict {
  if (!table) return fail(`A tabela \`${check.table}\` ainda não existe.`)
  const col = table.columns.find((c) => c.name === check.name)
  if (!col) return fail(`A tabela \`${check.table}\` não tem a coluna \`${check.name}\`.`)
  const at = `A coluna \`${check.name}\` existe, mas`
  if (check.type && col.type.toLowerCase() !== check.type.toLowerCase()) {
    return fail(`${at} o tipo é ${col.type} (esperado: ${check.type}).`)
  }
  if (check.nullable === false && col.nullable) return fail(`${at} aceita NULL (deveria ser obrigatória).`)
  if (check.nullable === true && !col.nullable) return fail(`${at} é obrigatória (deveria aceitar NULL).`)
  if (check.primaryKey && !col.isPrimaryKey) return fail(`${at} não é chave primária.`)
  if (check.unique && !col.isUnique) return fail(`${at} não é única.`)
  if (check.autoGenerated && !(col.identity || col.serial)) return fail(`${at} não gera valores automaticamente.`)
  if (check.hasDefault && col.default === null) return fail(`${at} não tem valor padrão (DEFAULT).`)
  return pass
}

async function checkResultMatches(
  engine: Engine,
  check: Extract<Check, { kind: 'resultMatches' }>,
  submission: Submission,
): Promise<Verdict> {
  const last = submission.lastOutcome
  if (!last) return fail('Execute a sua consulta (Ctrl+Enter) antes de verificar.')
  if (!last.ok) return fail('A sua última execução deu erro. Corrija e execute de novo.')
  const mine = lastTable(last)
  if (!mine) return fail('A sua última execução não devolveu uma tabela de resultados. Use um SELECT.')

  // queryRows e não run: run desfaz a transação em que o trial pode estar; queryRows de um trial (session) não mexe nela.
  const expected = await engine.queryRows(check.expectedSql).catch(() => undefined)
  if (!expected || expected.columns.length === 0) throw new Error(`expectedSql inválido: ${check.expectedSql}`)

  if (mine.columns.length !== expected.columns.length) {
    return fail(`Seu resultado tem ${mine.columns.length} coluna(s); o esperado tem ${expected.columns.length}.`)
  }
  if (!check.ignoreColumnNames) {
    const a = mine.columns.map((c) => c.toLowerCase())
    const b = expected.columns.map((c) => c.toLowerCase())
    if (a.some((c, i) => c !== b[i])) {
      return fail(`Os nomes das colunas não batem. Esperado: ${expected.columns.join(', ')}. Recebido: ${mine.columns.join(', ')}.`)
    }
  }
  if (mine.rows.length !== expected.rows.length) {
    return fail(`Seu resultado tem ${mine.rows.length} linha(s); o esperado tem ${expected.rows.length}.`)
  }
  const key = (row: unknown[]) => JSON.stringify(row.map(normalizeCell))
  const a = mine.rows.map(key)
  const b = expected.rows.map(key)
  if (!check.ordered) {
    a.sort()
    b.sort()
  }
  if (a.some((r, i) => r !== b[i])) {
    return fail(check.ordered ? 'Os valores ou a ordem das linhas não batem com o esperado.' : 'Os valores não batem com o esperado.')
  }
  return pass
}

/** Texto de todas as células do último resultado, para procurar um padrão (ex.: no plano de um EXPLAIN). */
function resultText(outcome: RunOutcome | null): string | null {
  if (!outcome?.ok) return null
  const last = lastTable(outcome)
  return last ? last.rows.map((r) => r.map((c) => (typeof c === 'object' ? JSON.stringify(c) : String(c))).join(' ')).join('\n') : null
}

async function evaluate(engine: Engine, schema: SchemaModel, check: Check, submission: Submission): Promise<Verdict> {
  const table = (name: string) => schema.tables.find((t) => t.name === name)
  switch (check.kind) {
    case 'lastRunRolledBack': {
      const last = submission.lastOutcome
      if (!last) return fail('Execute o script para ver o que acontece.')
      return last.rolledBack ? pass : fail('O script terminou com COMMIT ou ROLLBACK. Aqui a ideia é **esquecer** de confirmar: termine o script sem COMMIT.')
    }
    case 'view': {
      const v = schema.views.find((x) => x.id === check.name || x.name === check.name)
      if (!v) return fail(`A view \`${check.name}\` ainda não existe.`)
      if (check.materialized !== undefined && v.materialized !== check.materialized) {
        return fail(check.materialized ? 'A view existe, mas é comum: precisa ser MATERIALIZADA.' : 'A view existe, mas é materializada: aqui ela deveria ser comum.')
      }
      return pass
    }
    case 'function':
      return schema.functions.some((f) => f.name === check.name || f.id.startsWith(`${check.name}(`))
        ? pass
        : fail(`A função \`${check.name}\` ainda não existe.`)
    case 'trigger': {
      const t = table(check.table)
      if (!t) return fail(`A tabela \`${check.table}\` ainda não existe.`)
      if (t.triggers.length === 0) return fail(`A tabela \`${check.table}\` ainda não tem nenhum trigger.`)
      const found = t.triggers.some(
        (g) =>
          (!check.name || g.name === check.name) &&
          (!check.timing || g.timing === check.timing) &&
          (!check.event || g.events.includes(check.event)),
      )
      return found ? pass : fail('Existe um trigger, mas não com o nome, o momento (BEFORE/AFTER) e o evento pedidos.')
    }
    case 'index': {
      const t = table(check.table)
      if (!t) return fail(`A tabela \`${check.table}\` ainda não existe.`)
      const found = t.indexes
        .filter((i) => !i.primary)
        .some(
          (i) =>
            (check.columns === undefined || (i.columns.length === check.columns.length && i.columns.every((c, k) => c.toLowerCase() === check.columns![k].toLowerCase()))) &&
            (check.unique === undefined || i.unique === check.unique) &&
            (check.partial === undefined || (i.predicate !== null) === check.partial) &&
            (check.method === undefined || i.method === check.method),
        )
      return found ? pass : fail('Não existe um índice com essas características (confira colunas, ordem, UNIQUE e a condição parcial).')
    }
    case 'resultText': {
      const text = resultText(submission.lastOutcome)
      if (text === null) return fail(submission.lastOutcome?.ok === false ? 'A sua última execução deu erro.' : 'Execute o comando antes de verificar.')
      return new RegExp(check.pattern, check.flags ?? 'i').test(text) ? pass : fail('O resultado não mostra o que era esperado. Leia o plano com calma e ajuste.')
    }
    case 'tableExists':
      return table(check.table) ? pass : fail(`A tabela \`${check.table}\` ainda não existe.`)
    case 'tableMissing':
      return table(check.table) ? fail(`A tabela \`${check.table}\` ainda existe.`) : pass
    case 'column':
      return checkColumn(check, table(check.table))
    case 'constraint': {
      const t = table(check.table)
      if (!t) return fail(`A tabela \`${check.table}\` ainda não existe.`)
      const found = t.constraints.some(
        (c) =>
          c.kind === check.constraint &&
          (!check.columns || sameSet(c.columns, check.columns)) &&
          (!check.refTable || c.refTable === check.refTable) &&
          (!check.onDelete || c.onDelete === check.onDelete),
      )
      return found ? pass : fail('Essa regra ainda não existe na tabela (confira colunas e tabela referenciada).')
    }
    case 'rowCount': {
      if (!table(check.table)) return fail(`A tabela \`${check.table}\` ainda não existe.`)
      const where = check.where ? ` WHERE ${check.where}` : ''
      const [{ n }] = await engine.query<{ n: number }>(`SELECT count(*)::int AS n FROM "${check.table}"${where}`)
      if (check.equals !== undefined && n !== check.equals) return fail(`Foram encontradas ${n} linha(s); o esperado era ${check.equals}.`)
      if (check.atLeast !== undefined && n < check.atLeast) return fail(`Foram encontradas ${n} linha(s); o esperado era pelo menos ${check.atLeast}.`)
      return pass
    }
    case 'sqlTrue': {
      try {
        const rows = await engine.query<Record<string, unknown>>(check.sql)
        return Object.values(rows[0] ?? {})[0] === true ? pass : fail(check.message ?? 'Os dados ainda não estão como esperado.')
      } catch {
        return fail(check.message ?? 'Não foi possível conferir (a estrutura ainda não está pronta).')
      }
    }
    case 'sqlMatches': {
      const text = check.raw ? submission.sql : stripComments(submission.sql)
      return new RegExp(check.pattern, check.flags ?? 'i').test(text)
        ? pass
        : fail('Não encontrei isso no código que você executou neste passo.')
    }
    case 'resultMatches':
      return checkResultMatches(engine, check, submission)
    case 'lastRunError': {
      const last = submission.lastOutcome
      if (!last) return fail('Execute o comando para ver o erro acontecer.')
      if (last.ok) return fail('O comando funcionou, mas era para dar erro. Releia o objetivo.')
      if (check.code && last.error.code !== check.code) return fail(`Deu um erro diferente (${last.error.code}).`)
      return pass
    }
  }
}

export async function runChecks(engine: Engine, checks: Check[], submission: Submission): Promise<CheckResult[]> {
  // Se o banco não puder ser lido, as verificações que dependem dele falham com mensagem, em vez de derrubar a tela.
  const schema = await introspect(engine).catch(() => EMPTY_SCHEMA)
  const results: CheckResult[] = []
  for (const check of checks) {
    const verdict = await evaluate(engine, schema, check, submission)
    results.push({ ok: verdict.ok, label: describeCheck(check), message: verdict.ok ? undefined : verdict.message })
  }
  return results
}
